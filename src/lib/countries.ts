/** Full display name for an ISO alpha-3 code; falls back to the raw code. */
export function countryName(code: string | null | undefined): string {
  if (!code) return 'Not reported';
  const trimmed = code.trim().toUpperCase();
  return COUNTRIES[trimmed]?.name ?? trimmed;
}

/** Approximate country centroid for map arcs, or null when not catalogued. */
export function countryCentroid(code: string | null | undefined): [number, number] | null {
  if (!code) return null;
  return COUNTRIES[code.trim().toUpperCase()]?.centroid ?? null;
}

export function isKnownCountry(code: string | null | undefined): boolean {
  if (!code) return false;
  return Boolean(COUNTRIES[code.trim().toUpperCase()]);
}
